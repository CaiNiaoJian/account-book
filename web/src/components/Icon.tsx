export type IconName = keyof typeof ICON_PATHS

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'name'> {
  name: IconName | string
  /** 边长（px）。默认 18，与 15px 正文视觉重量匹配 */
  size?: number
  /** 描边宽度。默认 1.6（Regular 观感）；强调场景可用 2 */
  strokeWidth?: number
  /** 无障碍标签；提供后图标会被读屏朗读 */
  title?: string
}

/**
 * 图标组件。
 *
 * 关键实现细节：
 *   * `stroke="currentColor"` —— 颜色完全由父级文本色决定，主题切换自动跟随；
 *   * `vectorEffect="non-scaling-stroke"` 不启用（会破坏缩放一致性），
 *     改为在高 DPI 下由浏览器自然渲染；
 *   * `aria-hidden` 与 `role` 按是否提供 `title` 切换，保证读屏体验。
 */
export const Icon = forwardRef<SVGSVGElement, IconProps>(function Icon(
  { name, size = 18, strokeWidth = 1.6, title, className, ...rest },
  ref,
) {
  const paths = ICON_PATHS[name] ?? ICON_PATHS.about ?? []
  const labelled = Boolean(title)

  return (
    <svg
      ref={ref}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      role={labelled ? 'img' : undefined}
      aria-hidden={labelled ? undefined : true}
      aria-label={title}
      focusable="false"
      {...rest}
    >
      {labelled ? <title>{title}</title> : null}
      {paths.map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  )
})

